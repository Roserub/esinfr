const out = `/* Doucement icons: Lucide (ISC licence, lucide.dev) v0.460.0, stroke 1.5. Generated by tools/build-icons.js, do not edit by hand.
   IC(name) returns an inline SVG. Interface emojis are swapped for the matching icon as the page renders (text only,
   never attributes, inputs or the story/game pictures), so data and translations keep their emojis untouched. */
(function () {
  "use strict";
  const ICONS = ${JSON.stringify(ICONS)};
  const EMOJI = ${JSON.stringify(EMOJI)};
  const FILLED = { "★": 1, "♥": 1, "❤": 1, "💛": 1 };
  const svg = (n, cls) => ICONS[n] ? '<svg class="ic ic-' + n + (cls ? " " + cls : "") + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + ICONS[n] + "</svg>" : "";
  window.IC = svg;
  const keys = Object.keys(EMOJI).sort((a, b) => b.length - a.length).map(k => k.replace(/[.*+?^\${}()|[\\]\\\\]/g, "\\\\$&"));
  const RE = new RegExp("(" + keys.join("|") + ")\\uFE0F?", "gu");
  const TEST = new RegExp(RE.source, "u");
  // Never inside form fields, game pieces or story pictures; inside reading/dialogue text only on its buttons (🔊, 👁 …).
  const SKIP = "script,style,textarea,input,select,option,title,svg,.mem,.tok,.dx-item,.av-ava,.av-emo,.fx-fall,[data-raw]";
  const TEXT = ".bubble,.rd-p,.doc,.sms-bubble,.ord-line,.vc-live,.vc-cmp";
  function swapText(node) {
    const s = node.nodeValue; if (!s || !TEST.test(s)) return;
    const p = node.parentElement; if (!p || p.closest(SKIP) || (p.closest(TEXT) && !p.closest("button"))) return;
    const frag = document.createDocumentFragment(); let last = 0; RE.lastIndex = 0; let m;
    while ((m = RE.exec(s))) {
      if (m.index > last) frag.appendChild(document.createTextNode(s.slice(last, m.index)));
      const t = document.createElement("template"); t.innerHTML = svg(EMOJI[m[1]], FILLED[m[1]] ? "ic-fill" : ""); frag.appendChild(t.content);
      last = m.index + m[0].length;
    }
    if (last < s.length) frag.appendChild(document.createTextNode(s.slice(last)));
    node.parentNode.replaceChild(frag, node);
  }
  function scan(root) {
    if (!root) return;
    if (root.nodeType === 3) return swapText(root);
    if (root.nodeType !== 1 && root.nodeType !== 11) return;
    if (root.nodeType === 1 && root.hasAttribute("data-ic") && !root.firstElementChild) root.innerHTML = svg(root.getAttribute("data-ic"));
    root.querySelectorAll && root.querySelectorAll("[data-ic]:empty").forEach(el => { el.innerHTML = svg(el.getAttribute("data-ic")); });
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT), list = [];
    while (w.nextNode()) if (TEST.test(w.currentNode.nodeValue)) list.push(w.currentNode);
    list.forEach(swapText);
  }
  window.ICONS_SCAN = scan;
  function start() {
    scan(document.body);
    new MutationObserver(ms => { for (const m of ms) { if (m.type === "characterData") swapText(m.target); else m.addedNodes.forEach(scan); } })
      .observe(document.body, { childList: true, subtree: true, characterData: true });
  }
  if (document.body) start(); else document.addEventListener("DOMContentLoaded", start);
})();
`;
